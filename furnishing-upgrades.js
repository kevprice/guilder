export function furnitureEffects(s, uids) {
  const effects = {};
  for (const uid of new Set(uids)) {
    const item = s.guild.furniture.find((i) => i.uid === uid);
    const def = furnishingUpgrades.find((d) => d.id === item?.id);
    for (const [key, value] of Object.entries(def?.effects || {}))
      effects[key] = Math.max(effects[key] || 0, value);
  }
  return effects;
}
